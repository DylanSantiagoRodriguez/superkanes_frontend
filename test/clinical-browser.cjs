// Runs from the backend CRUD suite with a disposable database and real API.
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
module.exports = async function clinicalBrowser({ base, adminToken, user, org, revisionId }) {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: {width:1440,height:1000} });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const origin = process.env.TEST_FRONTEND_URL || 'http://localhost:5174';
  // Reuse the authenticated fixture session; all resource calls hit the real API.
  await page.route('**/api/v1/**', async route => {
    const url = new URL(route.request().url());
    if (url.pathname === '/api/v1/auth/refresh') return route.fulfill({json:{accessToken:adminToken,userId:user,expiresIn:3600},headers:{'access-control-allow-origin':origin,'access-control-allow-credentials':'true'}});
    if (route.request().method() === 'OPTIONS') return route.fulfill({status:204,headers:{'access-control-allow-origin':origin,'access-control-allow-credentials':'true','access-control-allow-headers':'*','access-control-allow-methods':'GET,POST,PATCH,DELETE,OPTIONS'}});
    const response = await route.fetch({url:base + url.pathname + url.search});
    await route.fulfill({response,headers:{...response.headers(),'access-control-allow-origin':origin,'access-control-allow-credentials':'true'}});
  });
  try {
    await page.goto(origin);
    await page.getByRole('button', {name:'Mascotas y tutores',exact:true}).click();
    await page.getByRole('button', {name:'Ver Luna',exact:true}).click();
    const image = page.getByRole('img', {name:'Foto de Luna',exact:true});
    await image.waitFor();
    assert.ok(await image.evaluate(img => img.complete && img.naturalWidth > 0));
    await page.getByRole('button',{name:'Editar',exact:true}).click();
    await page.locator('#field-nombre').fill('Luna sin guardar');
    await page.getByRole('button',{name:'Cerrar',exact:true}).click();
    await page.getByRole('button',{name:'Seguir editando',exact:true}).waitFor();
    await page.getByRole('button',{name:'Descartar cambios',exact:true}).click();
    await page.getByRole('button',{name:'Historia clínica',exact:true}).click();
    await page.getByRole('combobox',{name:'Sección',exact:true}).selectOption('revision_clinica');
    await page.getByRole('button',{name:'Ver Control',exact:true}).click();
    await page.getByRole('button',{name:'Editar',exact:true}).click();
    const editor = page.getByRole('textbox',{name:'Documento de historia clínica',exact:true});
    await editor.click();
    await editor.press('ControlOrMeta+End');
    await editor.press('Enter');
    await page.getByRole('button',{name:'Negrita',exact:true}).click();
    await editor.pressSequentially('Seguimiento desde el editor visual.');
    await editor.press('ControlOrMeta+a');
    await page.getByRole('combobox',{name:'Fuente',exact:true}).selectOption('Georgia');
    await page.getByRole('combobox',{name:'Tamaño de fuente',exact:true}).selectOption('14pt');
    await page.getByLabel('Color del texto',{exact:true}).fill('#245ba6');
    await page.getByRole('combobox',{name:'Resaltado',exact:true}).selectOption('#fff2a8');
    await page.getByRole('combobox',{name:'Interlineado',exact:true}).selectOption('2');
    await page.getByRole('button',{name:'Guardar',exact:true}).click();
    await page.getByText('Cambios guardados.',{exact:true}).waitFor();
    const response = await fetch(`${base}/api/v1/resources/revision_clinica/${revisionId}`, {headers:{Authorization:`Bearer ${adminToken}`,'X-Organization-Id':org}});
    assert.equal(response.status, 200);
    const saved = await response.json();
    assert.match(JSON.stringify(saved.data.documento), /Seguimiento desde el editor visual/);
    for (const format of ['Georgia', '14pt', '#245ba6', '#fff2a8', '"lineHeight":"2"']) assert.ok(JSON.stringify(saved.data.documento).includes(format), format);
    await page.getByRole('button',{name:'Ver Control',exact:true}).click();
    await page.getByRole('textbox',{name:'Documento de historia clínica',exact:true}).waitFor();
    assert.equal(await page.getByRole('textbox',{name:'Documento de historia clínica',exact:true}).getAttribute('contenteditable'), 'false');
    const formattedSpan = page.locator('.tiptap span[style*="font-family"]').first();
    assert.ok((await formattedSpan.getAttribute('style')).includes('Georgia'));
    await page.getByRole('combobox',{name:'Zoom del documento',exact:true}).selectOption('75');
    await page.getByRole('button',{name:'Cerrar',exact:true}).click();
    await page.getByRole('combobox',{name:'Sección',exact:true}).selectOption('atencion_clinica');
    await page.getByRole('button',{name:'Nuevo registro',exact:true}).click();
    await page.getByRole('heading',{name:'Nueva atención e historia clínica',exact:true}).waitFor();
    await page.locator('#field-mascota_id option').nth(1).waitFor({state:'attached'});
    await page.locator('#field-mascota_id').selectOption({index:1});
    await page.locator('#field-sede_id option').nth(1).waitFor({state:'attached'});
    await page.locator('#field-sede_id').selectOption({index:1});
    await page.locator('#field-fecha_atencion').fill('2026-11-03T10:00');
    await page.locator('#field-motivo_consulta').fill('Historia desde atención en navegador');
    assert.equal(await page.locator('#field-profesional_id').getAttribute('readonly'), '');
    await page.getByRole('button',{name:'Ir al documento',exact:true}).click();
    const initialEditor = page.getByRole('textbox',{name:'Documento de historia clínica',exact:true});
    await initialEditor.click();
    await initialEditor.press('ControlOrMeta+End');
    await initialEditor.pressSequentially('Paciente estable desde la atención.');
    // Reproduce clipboard/browser serialization: RGB colors and empty styles.
    await initialEditor.evaluate(element => element.editor.commands.insertContent('<p style="line-height:1.5"><span style="color:rgb(36,91,166);font-size:16px;font-family:Georgia">Texto pegado con formato desde navegador.</span></p>'));
    const savedAttention = page.waitForResponse(response => response.url().includes('/atencion_clinica/con-historia') && response.request().method() === 'POST');
    await page.getByRole('button',{name:'Guardar atención e historia',exact:true}).click();
    const attentionResponse = await savedAttention;
    assert.equal(attentionResponse.status(),201);
    const attentionData = (await attentionResponse.json()).data;
    await page.getByText('Cambios guardados.',{exact:true}).waitFor();
    const historyResponse = await fetch(`${base}/api/v1/resources/revision_clinica?filter=${encodeURIComponent(JSON.stringify({atencion_id:attentionData.id}))}`, {headers:{Authorization:`Bearer ${adminToken}`,'X-Organization-Id':org}});
    const histories = (await historyResponse.json()).data;
    assert.equal(histories.length,1);
    assert.equal(histories[0].motivo_consulta,'Historia desde atención en navegador');
    assert.match(JSON.stringify(histories[0].documento), /Paciente estable desde la atención/);
    const archiveResponse=await fetch(`${base}/api/v1/storage/clinical/pacientes/${attentionData.mascota_id}/documentos?revision_id=${histories[0].id}`,{headers:{Authorization:`Bearer ${adminToken}`,'X-Organization-Id':org}});
    assert.equal(archiveResponse.status,200);
    const archived=(await archiveResponse.json()).data;assert.equal(archived.length,1);
    assert.ok(JSON.stringify(histories[0].documento).includes('#245ba6'));
    const patient=(await (await fetch(`${base}/api/v1/resources/mascota/${attentionData.mascota_id}`,{headers:{Authorization:`Bearer ${adminToken}`,'X-Organization-Id':org}})).json()).data;
    await page.getByRole('button',{name:'Mascotas y tutores',exact:true}).click();
    // Fixture patients may share a name; the patient code identifies the row.
    await page.getByRole('row').filter({has:page.getByRole('cell',{name:patient.codigo,exact:true})}).getByRole('button',{name:`Ver ${patient.nombre}`,exact:true}).click();
    await page.getByRole('button',{name:'Abrir ficha clínica',exact:true}).click();
    await page.getByRole('button',{name:'Documentos del editor',exact:true}).click();
    const card=page.locator(`[data-document-id="${archived[0].id}"]`);
    await card.getByRole('button',{name:'Ver documento guardado',exact:true}).click();
    const storedEditor=page.getByRole('textbox',{name:'Documento de historia clínica',exact:true});
    await storedEditor.getByText('Texto pegado con formato desde navegador.',{exact:true}).waitFor();
    assert.equal(await storedEditor.getAttribute('contenteditable'),'false');
    const download=page.waitForEvent('download');
    await card.getByRole('button',{name:'Descargar original editable (JSON)',exact:true}).click();
    const file=await download;
    assert.deepEqual(JSON.parse(require('node:fs').readFileSync(await file.path(),'utf8')),histories[0].documento);
    assert.deepEqual(errors, []);
    console.log('OK: Chromium: foto real con nombre, descarte de cambios, documento extenso, edición, guardado y reapertura.');
  } catch (error) { await page.screenshot({path:'/tmp/superkanes-browser-failure.png'}); throw error; } finally { await page.unrouteAll({behavior:'wait'}); await browser.close(); }
};
